export const projetosRioKenlo = Object.freeze(projetosRio.filter(project => project.kind === "kenlo"));
export const projetosRioHabilitados = Object.freeze(projetosRio.filter(project => project.enabled));

export function getProjetoRio(name) {
  const normalized = String(name ?? "").toLowerCase();
  const project = projetosRio.find(item => item.collection.toLowerCase() === normalized);
  if (!project) throw new Error(`Projeto do Rio nao encontrado: ${name}`);
  return project;
}
